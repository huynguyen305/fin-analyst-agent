"""Turn a finished run (plus the human review) into vault files and a PR."""

from __future__ import annotations

import re
from datetime import date

from fin_agent.vault.render import (
    PROJECT_ROOT, QA_ROOT, company_paths, qa_note, render_hub, render_learning, render_qa_entry,
    render_report, render_review_queue, render_run_log, render_snapshot,
)
from fin_agent.vault.writer import SyncResult, VaultWriter

SKILLS_DIR = "Intelligence/Investment_Analysis/Analyst_Skills"


def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:50] or "note"


def learning_proposals(state: dict, run_id: str, day: str, review: dict | None) -> list[tuple[str, str]]:
    """(slug, content) pairs per the 'new discovery' rules in the Vault Sync Contract."""
    out = []
    req = state.get("request", {})
    tickers = req.get("tickers", [])
    sector = next(iter(state.get("datasets", {}).values()), {}).get("meta", {}).get("sector", "general")
    # 1-2. rule gap / conflict: a lens could not produce reconciled findings within the retry limit
    for lens, f in (state.get("findings") or {}).items():
        if f.get("low_confidence"):
            issues = (state.get("critic") or {}).get("issues", {}).get(lens, [])
            slug = _slug(f"{lens}-rule-gap-{'-'.join(tickers)}")
            out.append((slug, render_learning(
                run_id, day, slug, "rule_gap",
                f"The {lens} lens for {', '.join(tickers)} kept failing review after retries.",
                issues[:5] or ["see run log"],
                f"Add or sharpen a rule in the {lens} skill note so the analyst knows how to treat this case.",
                f"{SKILLS_DIR}/Lens-{lens.title().replace('_', '-')}.md", "low")))
    # 4. human correction at the review checkpoint
    if review and (review.get("feedback") or review.get("action") == "reject"):
        slug = _slug(f"human-correction-{'-'.join(tickers)}")
        out.append((slug, render_learning(
            run_id, day, slug, "human_correction",
            f"Huy {'rejected' if review.get('action') == 'reject' else 'approved with comments'} the {req.get('depth')} run on {', '.join(tickers)}.",
            [f"Feedback: {review.get('feedback') or '(none given)'}"],
            "Turn this feedback into a rule in the matching skill note (lens or sector) so future runs apply it.",
            f"{SKILLS_DIR}/Sector-{sector.title()}.md", "medium")))
    # 5. data quirk
    for w in state.get("dq_warnings", [])[:3]:
        slug = _slug(f"data-quirk-{w['ticker']}-{w['check']}")
        out.append((slug, render_learning(
            run_id, day, slug, "data_quirk", f"{w['ticker']} {w['period']}: {w['message']}",
            [f"source: {state['datasets'][w['ticker']]['meta']['source']}"],
            "Record the quirk for the data layer (mapping fix or known exception).",
            "fin-analyst-agent: fin_agent/data/providers", "medium")))
    return out


def sync_run(state: dict, run_id: str, writer: VaultWriter, review: dict | None = None,
             day: str | None = None) -> SyncResult:
    day = day or date.today().isoformat()
    req = state["request"]
    approved = not review or review.get("action") != "reject"
    tickers = req.get("tickers", [])

    def build(read):
        files: dict[str, str] = {f"{PROJECT_ROOT}/Runs/{day}_{run_id}.md": render_run_log(state, run_id, day, review)}
        if approved and state.get("recommendation"):
            t = tickers[0]
            p = company_paths(t, day, req["depth"])
            files[f"{p['report']}.md"] = render_report(state, run_id, day)
            note, csv_text = render_snapshot(state, day)
            files[f"{p['snapshot']}.md"] = note
            files[f"{p['snapshot']}.csv"] = csv_text
            files[f"{p['hub']}.md"] = render_hub(t, read(f"{p['hub']}.md"), p["report"], day,
                                                 state["recommendation"].get("call"), req["depth"])
        if approved and state.get("answer"):
            qpath = f"{QA_ROOT}/{day}.md"
            files[qpath] = qa_note(read(qpath), day, render_qa_entry(state, run_id))
        queue = f"{PROJECT_ROOT}/Learnings/_Review-Queue.md"
        queue_text = read(queue)
        for slug, content in learning_proposals(state, run_id, day, review):
            lpath = f"{PROJECT_ROOT}/Learnings/{day}_{slug}"
            files[f"{lpath}.md"] = content
            queue_text = render_review_queue(queue_text, lpath, slug)
        if queue_text is not None and queue_text != read(queue):
            files[queue] = queue_text
        return files

    kind = "report" if state.get("recommendation") else "Q&A"
    title = f"feat(fin-agent): {kind} {', '.join(tickers)} {day} ({run_id})"
    body = (f"Generated by fin-analyst-agent run `{run_id}`.\n\n"
            f"- Request: {state.get('user_input', '')}\n- Review: {(review or {}).get('action', 'n/a')}\n"
            f"- Guardrail events: {len(state.get('guardrail_log', []))}\n\n"
            "Learning proposals (if any) are under `Projects/FinAnalystAgent/Learnings/`.")
    return writer.sync(build, branch=f"fa/{day}-{run_id}", title=title, body=body)
