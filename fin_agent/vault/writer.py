"""Vault Writer: commit generated notes to a branch and open a PR (ADR-006).

Works in a temporary ``git worktree`` created from ``origin/main``, so it never
touches the checkout Obsidian (and Obsidian-Git) is using. Guardrails layer 4:
path allowlist, secret scan and wikilink check run before anything is committed.
"""

from __future__ import annotations

import re
import shutil
import subprocess
import tempfile
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable

from fin_agent.vault.render import ALLOWED_PREFIXES

SECRET_PATTERNS = [
    r"sk-ant-[A-Za-z0-9_-]{10,}", r"\bAKIA[0-9A-Z]{16}\b", r"\bghp_[A-Za-z0-9]{20,}\b", r"\bgithub_pat_[A-Za-z0-9_]{20,}",
    r"(?i)\b(?:api[_-]?key|secret|password)\s*[:=]\s*['\"]?[A-Za-z0-9/+_-]{12,}",
]
WIKILINK = re.compile(r"\[\[([^\]|#]+)")


class VaultSyncError(Exception):
    pass


@dataclass
class SyncResult:
    branch: str
    files: list[str]
    pushed: bool
    pr_url: str | None = None
    compare_url: str | None = None
    warnings: list[str] = field(default_factory=list)


def _git(cwd: Path, *args: str, check: bool = True) -> subprocess.CompletedProcess:
    res = subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True)
    if check and res.returncode != 0:
        raise VaultSyncError(f"git {' '.join(args)} failed: {res.stderr.strip()[:300]}")
    return res


def check_paths(files: dict[str, str]) -> None:
    for p in files:
        if ".." in Path(p).parts or p.startswith("/") or not p.startswith(ALLOWED_PREFIXES):
            raise VaultSyncError(f"Path not allowed by the sync contract: {p}")


def scan_secrets(files: dict[str, str]) -> None:
    for p, content in files.items():
        for pat in SECRET_PATTERNS:
            if re.search(pat, content):
                raise VaultSyncError(f"Possible secret in {p} (pattern {pat!r}); refusing to commit")


def broken_links(root: Path, files: dict[str, str]) -> list[str]:
    missing = []
    for p, content in files.items():
        if not p.endswith(".md"):
            continue
        for target in WIKILINK.findall(content):
            target = target.strip().replace("\\", "")
            if not ((root / f"{target}.md").exists() or (root / target).exists()):
                missing.append(f"{p} -> {target}")
    return missing


class VaultWriter:
    def __init__(self, vault_path: str | Path, base: str = "main", remote: str = "origin", push: bool = True):
        self.vault = Path(vault_path).expanduser()
        self.base, self.remote, self.push = base, remote, push
        if not (self.vault / ".git").exists():
            raise VaultSyncError(f"{self.vault} is not a git repository (set VAULT_PATH to your vault clone)")

    def sync(self, build: Callable[[Callable[[str], str | None]], dict[str, str]], branch: str,
             title: str, body: str = "") -> SyncResult:
        """``build(read)`` returns ``{path: content}``; ``read(path)`` gives the file's current text on the base."""
        has_remote = self.remote in _git(self.vault, "remote").stdout.split()
        start = self.base
        if has_remote:
            if _git(self.vault, "fetch", self.remote, self.base, check=False).returncode == 0:
                start = f"{self.remote}/{self.base}"
        tmp = Path(tempfile.mkdtemp(prefix="fa-vault-"))
        wt = tmp / "wt"
        _git(self.vault, "worktree", "add", "-b", branch, str(wt), start)
        pushed = False
        try:
            def read(path: str) -> str | None:
                f = wt / path
                return f.read_text(encoding="utf-8") if f.exists() else None

            files = build(read)
            check_paths(files)
            scan_secrets(files)
            for p, content in files.items():
                f = wt / p
                f.parent.mkdir(parents=True, exist_ok=True)
                f.write_text(content, encoding="utf-8")
            warnings = [f"broken wikilink: {b}" for b in broken_links(wt, files)]
            _git(wt, "add", "--", *files.keys())
            _git(wt, "-c", "user.name=Fin Analyst Agent", "-c", "user.email=fin-analyst-agent@localhost",
                 "commit", "-m", title, "-m", body or "Generated by fin-analyst-agent.")
            result = SyncResult(branch=branch, files=sorted(files), pushed=False, warnings=warnings)
            if self.push and has_remote:
                _git(wt, "push", "-u", self.remote, branch)
                result.pushed = pushed = True
                result.pr_url = self._open_pr(wt, branch, title, body)
                if not result.pr_url:
                    result.compare_url = self._compare_url(branch)
            return result
        finally:
            _git(self.vault, "worktree", "remove", "--force", str(wt), check=False)
            shutil.rmtree(tmp, ignore_errors=True)
            if pushed:  # the branch lives on the remote; keep the user's branch list clean
                _git(self.vault, "branch", "-D", branch, check=False)

    def _open_pr(self, wt: Path, branch: str, title: str, body: str) -> str | None:
        if not shutil.which("gh"):
            return None
        res = subprocess.run(["gh", "pr", "create", "--base", self.base, "--head", branch, "--title", title,
                              "--body", body or "Generated by fin-analyst-agent."], cwd=wt, capture_output=True, text=True)
        return res.stdout.strip().splitlines()[-1] if res.returncode == 0 and res.stdout.strip() else None

    def _compare_url(self, branch: str) -> str | None:
        url = _git(self.vault, "remote", "get-url", self.remote, check=False).stdout.strip()
        m = re.search(r"github\.com[:/](.+?)(?:\.git)?$", url)
        return f"https://github.com/{m.group(1)}/compare/{self.base}...{branch}?expand=1" if m else None
